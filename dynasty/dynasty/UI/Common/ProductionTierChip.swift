import SwiftUI

// MARK: - College Production Tier Display

extension CollegeProspect.CollegeProductionTier {

    /// Localized long form used in detail screens and comparison sheets.
    /// The enum rawValues are storage keys and are never shown directly.
    var displayName: String {
        switch self {
        case .elite:    return String(localized: "Elite")
        case .aboveAvg: return String(localized: "Above Avg")
        case .average:  return String(localized: "Average")
        case .belowAvg: return String(localized: "Below Avg")
        }
    }

    /// 2–3 character label for dense prospect list columns.
    var abbreviation: String {
        switch self {
        case .elite:    return String(localized: "ELI")
        case .aboveAvg: return String(localized: "AA")
        case .average:  return String(localized: "AVG")
        case .belowAvg: return String(localized: "BA")
        }
    }

    /// Letter grade the tier maps onto so production chips share the unified
    /// 5-tier palette used by every other grade in the app.
    private var equivalentLetter: String {
        switch self {
        case .elite:    return "A+"
        case .aboveAvg: return "A"
        case .average:  return "B"
        case .belowAvg: return "C"
        }
    }

    /// Chip tint — routed through `PositionGradeCalculator.gradeColorForLetter`
    /// so it can never drift from the letter-grade palette.
    var chipColor: Color {
        PositionGradeCalculator.gradeColorForLetter(equivalentLetter)
    }

    /// Sort rank, best tier first.
    var sortRank: Int {
        switch self {
        case .elite:    return 0
        case .aboveAvg: return 1
        case .average:  return 2
        case .belowAvg: return 3
        }
    }
}

