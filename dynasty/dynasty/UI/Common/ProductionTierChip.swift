// MARK: - NFL Readiness Bucket

/// Coarse day-one readiness bucket derived from `CollegeProspect.nflReadiness`.
/// Surfaced as a scouting insight line — readiness itself is never shown as a
/// raw number because it is a hidden generator value.
enum ProspectReadinessBucket {
    case proReady
    case developmental
    case project

    init(readiness: Int) {
        switch readiness {
        case 75...:   self = .proReady
        case 45..<75: self = .developmental
        default:      self = .project
        }
    }

    var label: String {
        switch self {
        case .proReady:      return String(localized: "Pro-ready")
        case .developmental: return String(localized: "Developmental")
        case .project:       return String(localized: "Project")
        }
    }

    var detail: String {
        switch self {
        case .proReady:
            return String(localized: "Can contribute from day one")
        case .developmental:
            return String(localized: "Rotational as a rookie, year-2 leap")
        case .project:
            return String(localized: "Needs seasoning before he is trusted")
        }
    }

    var icon: String {
        switch self {
        case .proReady:      return "checkmark.seal.fill"
        case .developmental: return "hourglass"
        case .project:       return "wrench.and.screwdriver.fill"
        }
    }

    var color: Color {
        switch self {
        case .proReady:      return .success
        case .developmental: return .accentBlue
        case .project:       return .warning
        }
    }
}

// MARK: - Production Tier Chip

/// Compact college-production tier chip (`ELI` / `AA` / `AVG` / `BA`).
///
/// Used as the `PROD` column in every prospect list. College production is a
/// real but imperfect signal generated by `DraftClassBuilder`, so it reads as a
/// separate axis from the scout's overall grade.
struct ProductionTierChip: View {
    let tier: CollegeProspect.CollegeProductionTier

    /// Column width the chip is centered in. `nil` sizes to content.
    var width: CGFloat? = 40

    /// Draws the tinted capsule behind the label.
    var showsBackground: Bool = true

    var fontSize: CGFloat = 9

    var body: some View {
        Text(tier.abbreviation)
            .font(.system(size: fontSize, weight: .heavy))
            .foregroundStyle(tier.chipColor)
            .lineLimit(1)
            .minimumScaleFactor(0.7)
            .padding(.horizontal, showsBackground ? 4 : 0)
            .padding(.vertical, showsBackground ? 2 : 0)
            .background {
                if showsBackground {
                    RoundedRectangle(cornerRadius: 3)
                        .fill(tier.chipColor.opacity(0.15))
                }
            }
            .frame(width: width, alignment: .center)
            .accessibilityLabel(Text("College production: \(tier.displayName)"))
    }
}

/// Micro production label for panels that have no room for a column — renders
/// as an inline `PROD ELI` pair under the prospect's name.
struct ProductionMicroLabel: View {
    let tier: CollegeProspect.CollegeProductionTier
    var fontSize: CGFloat = 8

    var body: some View {
        HStack(spacing: 2) {
            Text("PROD")
                .font(.system(size: fontSize, weight: .semibold))
                .foregroundStyle(Color.textTertiary)
            Text(tier.abbreviation)
                .font(.system(size: fontSize, weight: .heavy))
                .foregroundStyle(tier.chipColor)
        }
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(Text("College production: \(tier.displayName)"))
    }
}
